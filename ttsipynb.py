import re

metadata_path = "/content/tts_ready_dataset/metadata.csv"

# Basic number to Swahili words mapping
num_map = {
    "0": "zero", "1": "jamo", "2": "mbwegze", "3": "tatu", "4": "nne",
    "5": "tano", "6": "sita", "7": "saba", "8": "nane", "9": "tisa",
    "10": "kumi", "11": "kumi na moja", "12": "kumi na mbili",
    "16": "kumi na sita", "20": "mbao", "80": "themanini",
    "100": "soo", "1000": "elfu moja", "16000": "elfu kumi na sita",
}

def replace_numbers(text):
    # Strip commas inside numbers (e.g. 16,000 -> 16000)
    text = re.sub(r'(?<=\d),(?=\d)', '', text)
    # Replace known numbers
    def lookup(match):
        val = match.group(0)
        return num_map.get(val, val)

    # Run lookup
    text = re.sub(r'\b\d+\b', lookup, text)
    # Remove any leftover special characters that aren't basic punctuation
    text = re.sub(r'[%$#@&*\/\\\[\]_+=<>]', ' ', text)
    return re.sub(r'\s+', ' ', text).strip()

# Clean metadata.csv
cleaned_lines = []
with open(metadata_path, "r", encoding="utf-8") as f:
    for line in f:
        parts = line.strip().split("|")
        if len(parts) >= 2:
            wav_id = parts[0]
            transcript = replace_numbers(parts[1])
            normalized = replace_numbers(parts[-1])
            cleaned_lines.append(f"{wav_id}|{transcript}|{normalized}\n")

with open(metadata_path, "w", encoding="utf-8") as f:
    f.writelines(cleaned_lines)

print(f"Cleaned {len(cleaned_lines)} rows in metadata.csv. Numbers and rogue symbols removed!")

